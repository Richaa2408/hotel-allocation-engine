-- StayFlow schema. Portable SQL: runs on PostgreSQL (app) and H2 in PostgreSQL mode (tests).
-- Dates are nights: a stay uses check_in up to the night before check_out.

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE room (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number       VARCHAR(10) NOT NULL UNIQUE,
    type         VARCHAR(20) NOT NULL,
    floor        INTEGER     NOT NULL,
    accessible   BOOLEAN     NOT NULL,
    capacity     INTEGER     NOT NULL,
    housekeeping VARCHAR(20) NOT NULL
);

CREATE TABLE guest (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email     VARCHAR(254),
    phone     VARCHAR(32),
    email_key VARCHAR(254),
    phone_key VARCHAR(32)
);
CREATE INDEX idx_guest_email_key ON guest (email_key);

CREATE TABLE reservation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference        VARCHAR(20)  UNIQUE,
    guest_id         BIGINT       NOT NULL REFERENCES guest (id),
    room_type        VARCHAR(20)  NOT NULL,
    check_in         DATE         NOT NULL,
    check_out        DATE         NOT NULL,
    rooms            INTEGER      NOT NULL,
    adults           INTEGER      NOT NULL,
    needs_accessible BOOLEAN      NOT NULL,
    max_floor        INTEGER,
    preferred_floor  INTEGER,
    accepts_upgrade  BOOLEAN      NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    screening        VARCHAR(20)  NOT NULL,
    block_reason     VARCHAR(200),
    idempotency_key  VARCHAR(64)  UNIQUE,
    notes            VARCHAR(500),
    created_by       VARCHAR(50)  NOT NULL,
    created_at       TIMESTAMP    NOT NULL,
    updated_at       TIMESTAMP    NOT NULL,
    CONSTRAINT chk_reservation_dates CHECK (check_out > check_in),
    CONSTRAINT chk_reservation_rooms CHECK (rooms >= 1)
);
CREATE INDEX idx_reservation_check_in ON reservation (check_in);
CREATE INDEX idx_reservation_check_out ON reservation (check_out);
CREATE INDEX idx_reservation_status ON reservation (status);

-- One row per room in a reservation: the unit the assignment engine matches to a physical room.
CREATE TABLE room_request (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT  NOT NULL REFERENCES reservation (id),
    seq            INTEGER NOT NULL,
    CONSTRAINT uq_room_request UNIQUE (reservation_id, seq)
);

-- Every assignment ever made; active = current. Inactive rows are the reassignment history.
CREATE TABLE room_assignment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id  BIGINT       NOT NULL REFERENCES room_request (id),
    room_id     BIGINT       NOT NULL REFERENCES room (id),
    method      VARCHAR(20)  NOT NULL,
    active      BOOLEAN      NOT NULL,
    reason      VARCHAR(200),
    assigned_by VARCHAR(50)  NOT NULL,
    assigned_at TIMESTAMP    NOT NULL,
    released_at TIMESTAMP
);
CREATE INDEX idx_assignment_room ON room_assignment (room_id, active);
CREATE INDEX idx_assignment_request ON room_assignment (request_id, active);

CREATE TABLE maintenance_block (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id    BIGINT       NOT NULL REFERENCES room (id),
    start_date DATE         NOT NULL,
    end_date   DATE         NOT NULL,
    reason     VARCHAR(200) NOT NULL,
    active     BOOLEAN      NOT NULL,
    created_by VARCHAR(50)  NOT NULL,
    created_at TIMESTAMP    NOT NULL,
    CONSTRAINT chk_block_dates CHECK (end_date > start_date)
);
CREATE INDEX idx_block_room ON maintenance_block (room_id, active);

CREATE TABLE watchlist_entry (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind          VARCHAR(10)  NOT NULL,
    value_key     VARCHAR(270) NOT NULL UNIQUE,
    display_value VARCHAR(254) NOT NULL,
    reason        VARCHAR(200) NOT NULL,
    created_at    TIMESTAMP    NOT NULL
);

CREATE TABLE audit_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          TIMESTAMP    NOT NULL,
    actor       VARCHAR(50)  NOT NULL,
    action      VARCHAR(40)  NOT NULL,
    entity_type VARCHAR(30)  NOT NULL,
    entity_ref  VARCHAR(40),
    detail      VARCHAR(500) NOT NULL
);
CREATE INDEX idx_audit_at ON audit_event (at);
